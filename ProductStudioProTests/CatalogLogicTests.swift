    func testSessionMetadataBundleRoundTrip() throws {
        let sessionID = UUID()
        let productMeta = ProductMetadata(sku: "SKU-1", productName: "Widget")
        let product = Product(id: UUID(), metadata: productMeta, imageAssetIDs: [UUID()])
        let imageAsset = ImageAsset(
            id: product.imageAssetIDs[0],
            productID: product.id,
            metadata: ImageMetadata(filename: "Widget.jpg", width: 1000, height: 1000)
        )
        let bundle = SessionMetadataBundle(
            project: ProjectMetadata(id: sessionID, projectName: "Launch"),
            products: [product],
            imageAssets: [imageAsset]
        )
        let data = try XCTUnwrap(try? JSONEncoder().encode(bundle))
        let decoded = try XCTUnwrap(try? JSONDecoder().decode(SessionMetadataBundle.self, from: data))
        XCTAssertEqual(decoded.project.projectName, "Launch")
        XCTAssertEqual(decoded.products.count, 1)
        XCTAssertEqual(decoded.imageAssets.count, 1)
    }
