        XCTAssertEqual(bundle.products[0].metadata.sku, "012345678905")
        XCTAssertEqual(bundle.products[0].metadata.brand, "Acme")
        XCTAssertEqual(bundle.products[0].metadata.marketplace, "Amazon")
        XCTAssertEqual(bundle.imageAssets[0].metadata.sequence, 3)
        XCTAssertEqual(bundle.imageAssets[0].metadata.backgroundRemoved, true)
    }

